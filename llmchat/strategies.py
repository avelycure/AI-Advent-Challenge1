"""Четыре способа поставить модели одну и ту же задачу.

Замысел опыта: задача одна, меняется только способ спросить. Сравниваются
две разные вещи — верность итога и качество объяснения. Первую считает код,
вторую оценивает отдельная модель по заданным признакам, потому что «полнее»
и «понятнее» машинально не измерить.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Callable, List, Optional

# --------------------------------------------------------------------------
# Задача
# --------------------------------------------------------------------------

@dataclass(frozen=True)
class Task:
    question: str
    answer: int
    trap: Optional[int] = None      # правдоподобный неверный ответ
    trap_note: str = ""
    verify: str = ""                # как истина посчитана, для отчёта


DIGIT_TASK = Task(
    question=("Сколько раз цифра 7 встречается при записи всех целых чисел "
              "от 1 до 2024 включительно?"),
    answer=602,
    trap=544,
    trap_note="столько чисел содержат хотя бы одну семёрку — частая подмена вопроса",
    verify="sum(str(i).count('7') for i in range(1, 2025))",
)


# --------------------------------------------------------------------------
# Способы
# --------------------------------------------------------------------------

@dataclass
class Strategy:
    key: str
    title: str
    description: str
    # Возвращает список сообщений. Некоторым способам нужен предварительный
    # запрос к модели — они получают её через параметр ask.
    build: Callable[[Task, Callable[[str], str]], List[dict]]
    accent: str = "cyan"
    extra_calls: int = 0
    # Промежуточный результат, который стоит показать пользователю
    # (например, промпт, который модель написала себе сама).
    artifact: Optional[str] = field(default=None, compare=False)


def _direct(task: Task, ask) -> List[dict]:
    # Никаких добавок: только сам вопрос.
    return [{"role": "user", "content": task.question}]


def _step_by_step(task: Task, ask) -> List[dict]:
    return [{"role": "user", "content":
             task.question + "\n\nРешай пошагово: разбей задачу на шаги, "
             "показывай промежуточные вычисления и только потом назови итог."}]


SELF_PROMPT_REQUEST = (
    "Ниже задача. Не решай её. Вместо этого напиши промпт, который поможет "
    "языковой модели решить её как можно надёжнее: укажи, на что обратить "
    "внимание, какие ошибки типичны и как проверить результат. "
    "Верни только текст промпта, без пояснений.\n\nЗадача: {question}"
)


def _self_prompt(task: Task, ask) -> List[dict]:
    prompt = ask(SELF_PROMPT_REQUEST.format(question=task.question)).strip()
    return [{"role": "user", "content": prompt}]


EXPERTS_SYSTEM = (
    "В обсуждении участвуют три специалиста, и каждый отвечает от своего лица:\n"
    "• Аналитик — разбирает условие, ищет подмену вопроса и краевые случаи;\n"
    "• Инженер — предлагает способ расчёта и доводит его до числа;\n"
    "• Критик — ищет ошибки в рассуждениях двух предыдущих и проверяет итог "
    "другим способом.\n\n"
    "Формат ответа строго такой:\n"
    "### Аналитик\n<разбор>\n### Инженер\n<расчёт>\n### Критик\n<проверка>\n"
    "### Согласованный ответ\n<итоговое число и одна фраза обоснования>"
)


def _experts(task: Task, ask) -> List[dict]:
    return [{"role": "system", "content": EXPERTS_SYSTEM},
            {"role": "user", "content": task.question}]


