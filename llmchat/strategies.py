JUDGE_CRITERIA = [
    ("полнота", "разобрано ли условие, доведено ли решение до конца"),
    ("ясность", "легко ли проследить ход мысли, есть ли структура"),
    ("обоснованность", "объяснено ли, почему способ верен, есть ли проверка"),
]

JUDGE_PROMPT = (
    "Ты оцениваешь качество объяснения, а не только правильность числа.\n\n"
    "Задача: {question}\n"
    "Верный ответ: {answer}\n\n"
    "Ответ, который надо оценить:\n---\n{text}\n---\n\n"
    "Оцени по трём признакам целыми числами от 1 до 5:\n"
    "полнота — разобрано ли условие, доведено ли решение до конца;\n"
    "ясность — легко ли проследить ход мысли, есть ли структура;\n"
    "обоснованность — объяснено ли, почему способ верен, есть ли проверка.\n\n"
    "Ответь строго тремя строками и ничем больше:\n"
    "полнота: <число>\nясность: <число>\nобоснованность: <число>"
)


def parse_scores(text: str) -> dict:
    scores = {}
    for name, _ in JUDGE_CRITERIA:
        match = re.search(name + r"\D{0,10}([1-5])", text, re.IGNORECASE)
        if match:
            scores[name] = int(match.group(1))
    return scores
