# --------------------------------------------------------------------------
# Извлечение итога
# --------------------------------------------------------------------------

# Число берём только вплотную к ключевому слову: между ними допустимы лишь
# разделители и связки. Иначе «Итого цифра 7 встречается 602 раза» даёт 7 —
# шаблон хватает первое попавшееся число, а не итоговое.
_NUM = r"\**\s*(\d[\d\s\u00a0]{0,8}\d|\d)"
_LINK = r"(?:\s|[:\-—–=])*(?:равен|равно|равна|составляет|это|—|-)?(?:\s|[:\-—–=])*"

ANSWER_PATTERNS = [
    re.compile(r"(?:ответ|итого?в\w*|итог)" + _LINK + _NUM, re.IGNORECASE),
    re.compile(r"встречается" + _LINK + _NUM + r"\s*раз", re.IGNORECASE),
    re.compile(_NUM + r"\s*раз(?:а|ов)?\b", re.IGNORECASE),
    re.compile(r"=" + _LINK + _NUM + r"\s*\**\s*$", re.MULTILINE),
]


def extract_answer(text: str) -> Optional[int]:
    """Достать итоговое число из свободного текста.

    Сначала ищем явные обороты вроде «ответ» и «итог», просматривая текст
    с конца: модели часто повторяют промежуточные числа, и последнее
    упоминание надёжнее первого.
    """
    for pattern in ANSWER_PATTERNS:
        found = pattern.findall(text)
        if found:
            raw = found[-1].replace(" ", "").replace(" ", "")
            if raw.isdigit():
                return int(raw)
    tail = text[-160:]
    numbers = re.findall(r"\d[\d\s]{0,8}\d|\d", tail)
    if numbers:
        raw = numbers[-1].replace(" ", "").replace(" ", "")
        if raw.isdigit():
            return int(raw)
    return None


EXTRACT_PROMPT = (
    "Ниже текст с решением задачи. Верни ТОЛЬКО то число, которое автор называет "
    "итоговым ответом, без слов и без пояснений. Если итогового числа в тексте "
    "нет, верни слово: нет\n\n---\n{text}\n---"
)


def parse_extracted(text: str) -> Optional[int]:
    """Разобрать ответ модели-извлекателя: только число или «нет»."""
    cleaned = text.strip().replace("\u00a0", "").replace(" ", "")
    match = re.search(r"-?\d+", cleaned)
    if match and "нет" not in text.strip().lower()[:6]:
        try:
            return int(match.group(0))
        except ValueError:
            return None
    return None


